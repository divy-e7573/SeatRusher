/**
 * Read-API contracts for shows and seat maps.
 *
 * Money is always an integer number of paise (1 rupee = 100 paise) so no client
 * ever has to do floating-point arithmetic on prices. See ADR 0002.
 */

export const SEAT_CATEGORY = {
  REGULAR: 'REGULAR',
  PREMIUM: 'PREMIUM',
  RECLINER: 'RECLINER',
} as const;

export type SeatCategory = (typeof SEAT_CATEGORY)[keyof typeof SEAT_CATEGORY];

/**
 * Effective state of a seat for one show.
 *
 * The three values are ordered by authority, and that order is applied when a
 * seat is both booked and held: a seat in Postgres wins, because Postgres is
 * the final source of truth (AGENTS.md invariant 1).
 */
export const SEAT_STATUS = {
  AVAILABLE: 'AVAILABLE',
  /** Locked by a live Redis hold (Phase 3). Not durable; disappears on expiry. */
  HELD: 'HELD',
  BOOKED: 'BOOKED',
} as const;

export type SeatStatus = (typeof SEAT_STATUS)[keyof typeof SEAT_STATUS];

export interface ShowPrice {
  category: SeatCategory;
  amountPaise: number;
}

/** Row shape of `GET /shows`. */
export interface ShowSummary {
  id: string;
  title: string;
  synopsis: string | null;
  screenId: string;
  screenName: string;
  venueName: string;
  venueCity: string;
  /** ISO-8601 UTC timestamp generated by the server (never a client clock). */
  startTime: string;
  prices: ShowPrice[];
  totalSeats: number;
  availableSeats: number;
}

/** Row shape of `GET /shows/:id` (same fields, single show). */
export type ShowDetail = ShowSummary;

export interface ShowSeat {
  id: string;
  rowLabel: string;
  seatNumber: number;
  category: SeatCategory;
  /** Price for this seat's category on this show, in paise. */
  pricePaise: number;
  status: SeatStatus;
}

/** Response of `GET /shows/:id/seats`. */
export interface ShowSeats {
  showId: string;
  screenId: string;
  screenName: string;
  venueName: string;
  totalSeats: number;
  availableSeats: number;
  seats: ShowSeat[];
}
